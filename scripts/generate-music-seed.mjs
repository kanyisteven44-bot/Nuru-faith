/**
 * Regenerate supabase/seeds/multilingual_sources.sql from the reviewed list.
 *
 * Run this after scripts/resolve-music-sources.mjs adds artists, so the seed
 * and content/media-source-review.json can never drift apart. Writing the
 * seed by hand is how a channel id ends up in one file and not the other.
 *
 * The seed is additive: both inserts end in `do nothing`, so re-running it
 * never overwrites an editorial decision already made in the database.
 *
 *   node scripts/generate-music-seed.mjs
 *   node scripts/generate-music-seed.mjs --check   # verify, write nothing
 */
import { readFile, writeFile } from "node:fs/promises";

const REVIEWED = "content/media-source-review.json";
const SEED = "supabase/seeds/multilingual_sources.sql";
const CHECK = process.argv.includes("--check");

const reviewed = JSON.parse(await readFile(REVIEWED, "utf8"));
if (!Array.isArray(reviewed) || !reviewed.length) {
  console.error(`${REVIEWED} is empty or not a list.`);
  process.exit(1);
}

// Every row must carry the proof that it was checked against a real channel.
const invalid = reviewed.filter(
  (r) =>
    !/^UC[\w-]{22}$/.test(r.youtube_channel_id ?? "") ||
    !r.name ||
    !r.verification_url?.endsWith(r.youtube_channel_id) ||
    !r.verified_at,
);
if (invalid.length) {
  console.error(
    `${invalid.length} reviewed entries are missing a valid channel id, name, ` +
      `matching verification_url or verified_at:\n` +
      invalid.map((r) => `  ${r.name ?? "(unnamed)"}`).join("\n"),
  );
  process.exit(1);
}

const seenChannel = new Map();
for (const row of reviewed) {
  if (seenChannel.has(row.youtube_channel_id)) {
    console.error(
      `Duplicate channel ${row.youtube_channel_id}: ` +
        `"${seenChannel.get(row.youtube_channel_id)}" and "${row.name}".`,
    );
    process.exit(1);
  }
  seenChannel.set(row.youtube_channel_id, row.name);
}

const stamp = reviewed.reduce((latest, r) => (r.verified_at > latest ? r.verified_at : latest), "");
const payload = JSON.stringify(reviewed);

const sql = `-- Reviewed identities, ${stamp}. Metadata only; never overwrite editorial decisions.
-- Generated by scripts/generate-music-seed.mjs from ${REVIEWED} — do not edit by hand.
with reviewed as (select * from jsonb_to_recordset($nuru$${payload}$nuru$::jsonb) as r(name text,youtube_channel_id text,content_kind text,language_codes text[],avatar_url text,verification_url text))
insert into public.media_sources(name,source_type,youtube_channel_id,description,avatar_url,is_verified,is_approved,content_kind,language_codes)
select name,'youtube',youtube_channel_id,'Reviewed '||content_kind||' creator. Language collections: '||array_to_string(language_codes,', ')||'. Identity checked ${stamp}: '||verification_url,avatar_url,true,true,content_kind,language_codes from reviewed
on conflict (youtube_channel_id) where youtube_channel_id is not null do nothing;
with reviewed as (select * from jsonb_to_recordset($nuru$${payload}$nuru$::jsonb) as r(name text,youtube_channel_id text,content_kind text,verification_url text))
insert into public.approved_youtube_channels(channel_id,channel_name,category,is_verified,trust_level,notes)
select youtube_channel_id,name,case when content_kind='music' then 'worship' else 'teaching' end,true,'verified','Identity matched to public creator channel on ${stamp}: '||verification_url from reviewed
on conflict(channel_id) do nothing;
select content_kind,count(*) from public.media_sources where is_approved and content_kind in ('music','podcast') group by content_kind;
`;

const music = reviewed.filter((r) => r.content_kind === "music").length;
const languages = new Set(reviewed.flatMap((r) => r.language_codes ?? []));

if (CHECK) {
  const current = await readFile(SEED, "utf8").catch(() => "");
  if (current.trim() === sql.trim()) {
    console.log(`${SEED} is up to date (${reviewed.length} sources).`);
  } else {
    console.error(`${SEED} is stale. Run: node scripts/generate-music-seed.mjs`);
    process.exit(1);
  }
} else {
  await writeFile(SEED, sql);
  console.log(`Wrote ${SEED}`);
}

console.log(
  `${reviewed.length} reviewed sources (${music} music), ` +
    `${languages.size} languages: ${[...languages].sort().join(", ")}`,
);
