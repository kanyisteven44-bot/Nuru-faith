drop policy if exists "chat media read participants" on storage.objects;
create policy "chat media read participants"
on storage.objects for select
to authenticated
using (
  bucket_id = 'chat-media'
  and (
    (
      (storage.foldername(name))[1] = 'direct'
      and (
        (storage.foldername(name))[2] = (select auth.uid())::text
        or (storage.foldername(name))[3] = (select auth.uid())::text
      )
    )
    or
    (
      (storage.foldername(name))[1] = 'group'
      and case
        when (storage.foldername(name))[2] ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
        then private.is_group_member((select auth.uid()), ((storage.foldername(name))[2])::uuid)
        else false
      end
    )
  )
);

