create table if not exists public.call_sessions (
  id uuid primary key default gen_random_uuid(),
  caller_id uuid not null references auth.users(id) on delete cascade,
  callee_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('audio','video')),
  status text not null default 'ringing' check (status in ('ringing','active','declined','ended','missed')),
  offer jsonb not null,
  answer jsonb,
  created_at timestamptz not null default now(),
  answered_at timestamptz,
  ended_at timestamptz,
  constraint call_sessions_not_self check (caller_id <> callee_id)
);

create index if not exists call_sessions_callee_status_created
  on public.call_sessions (callee_id, status, created_at desc);

create index if not exists call_sessions_caller_created
  on public.call_sessions (caller_id, created_at desc);

alter table public.call_sessions enable row level security;
revoke all on public.call_sessions from anon;
grant select, insert on public.call_sessions to authenticated;
grant update (status, answer, answered_at, ended_at) on public.call_sessions to authenticated;

drop policy if exists "call participants read" on public.call_sessions;
create policy "call participants read"
on public.call_sessions for select
to authenticated
using (
  (select auth.uid()) = caller_id
  or (select auth.uid()) = callee_id
);

drop policy if exists "caller creates call" on public.call_sessions;
create policy "caller creates call"
on public.call_sessions for insert
to authenticated
with check (
  (select auth.uid()) = caller_id
  and caller_id <> callee_id
);

drop policy if exists "call participants update" on public.call_sessions;
create policy "call participants update"
on public.call_sessions for update
to authenticated
using (
  (select auth.uid()) = caller_id
  or (select auth.uid()) = callee_id
)
with check (
  (select auth.uid()) = caller_id
  or (select auth.uid()) = callee_id
);

create table if not exists public.call_ice_candidates (
  id bigint generated by default as identity primary key,
  call_id uuid not null references public.call_sessions(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  candidate jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists call_ice_candidates_call_created
  on public.call_ice_candidates (call_id, created_at, id);

alter table public.call_ice_candidates enable row level security;
revoke all on public.call_ice_candidates from anon;
grant select, insert on public.call_ice_candidates to authenticated;

drop policy if exists "call candidates participants read" on public.call_ice_candidates;
create policy "call candidates participants read"
on public.call_ice_candidates for select
to authenticated
using (
  exists (
    select 1
    from public.call_sessions c
    where c.id = call_ice_candidates.call_id
      and ((select auth.uid()) = c.caller_id or (select auth.uid()) = c.callee_id)
  )
);

drop policy if exists "call candidates participant insert" on public.call_ice_candidates;
create policy "call candidates participant insert"
on public.call_ice_candidates for insert
to authenticated
with check (
  user_id = (select auth.uid())
  and exists (
    select 1
    from public.call_sessions c
    where c.id = call_ice_candidates.call_id
      and ((select auth.uid()) = c.caller_id or (select auth.uid()) = c.callee_id)
  )
);

